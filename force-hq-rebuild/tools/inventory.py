#!/usr/bin/env python3
"""Dump the text of every section's Learn steps, Challenge missions and Check questions to docs/inventory.txt.

Used for audits (for example the reading and writing skills audit) so nobody has to read the whole source.
Run after `python3 build.py`:  python3 tools/inventory.py
"""
import asyncio, json, os, re
from playwright.async_api import async_playwright

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'docs', 'inventory.txt')

JS = r"""() => {
  const C = __fhq.CHDATA, plain = h => String(h == null ? '' : h).replace(/<br\s*\/?>/g, ' ').replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\s+/g, ' ').trim();
  const qline = q => {
    const bits = [`[${q.id} · ${q.type}${q.obj ? ' · ' + [].concat(q.obj).join(',') : ''}${q.marks ? ' · ' + q.marks + ' marks' : ''}]`, plain(q.p || q.q)];
    if (q.opts) bits.push('Options: ' + q.opts.map(plain).join(' | '));
    if (q.a !== undefined && typeof q.a !== 'function') bits.push('Answer: ' + plain(JSON.stringify(q.a)));
    if (q.rows) bits.push('Rows: ' + q.rows.map(r => plain(Array.isArray(r) ? r.join(' / ') : (r.p || r.t || JSON.stringify(r)))).join(' | '));
    if (q.items) bits.push('Items: ' + q.items.map(r => plain(typeof r === 'string' ? r : (r.t || r.p || JSON.stringify(r)))).join(' | '));
    if (q.model) bits.push('Model: ' + plain(q.model));
    if (q.work) bits.push('Working: ' + plain(q.work));
    if (q.ticks) bits.push('Ticks: ' + q.ticks.map(plain).join(' | '));
    return bits.join('\n      ');
  };
  return SECTIONS_LIST.map(sec => {
    const d = C[sec.id] || {}, L = [];
    L.push(`\n######## ${sec.id} · Chapter ${sec.n} ${sec.part}: ${sec.title}`);
    L.push(`GOAL: ${plain(sec.goal)}`);
    (d.steps || []).forEach((s, i) => {
      L.push(`\n== Learn ${i + 1} (${s.id}): ${plain(s.title)}`);
      (s.cards || []).forEach(c => L.push(`  CARD: ${plain(c.html || c)}`));
      if (s.predict) L.push(`  PREDICT: ${plain(s.predict.q)}${s.predict.opts ? ' Options: ' + s.predict.opts.map(plain).join(' | ') : ''}`);
      (s.tasks || []).forEach(t => L.push(`  TASK: ${plain(Array.isArray(t) ? t[0] : t)}`));
      (s.qs || []).forEach(q => L.push('  Q ' + qline(q)));
      if (s.after) L.push(`  AFTER: ${plain(s.after)}`);
    });
    if (d.challenge) L.push(`\n== Challenge: ${(Array.isArray(d.challenge) ? d.challenge : (d.challenge.missions || [])).map(m => typeof m === 'string' ? m : `${m.id} ${plain(m.title)}: ${plain(m.brief || m.goal || '')}`).join('\n   ')}`);
    L.push(`\n== Check`);
    (d.review || []).forEach(q => L.push('  Q ' + qline(q)));
    return L.join('\n');
  }).join('\n');
}"""

async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page()
        await pg.goto('file://' + os.path.join(ROOT, 'dist', 'test.html')); await pg.wait_for_timeout(500)
        await pg.evaluate("() => { window.SECTIONS_LIST = __fhq.ev('SECTIONS') }")
        txt = await pg.evaluate(JS)
        await b.close()
    open(OUT, 'w', encoding='utf-8').write('Force HQ inventory: every section\'s Learn steps, Challenge and Check (generated by tools/inventory.py; do not edit)\n' + txt + '\n')
    print(f'wrote {OUT}: {len(txt)//1024} KB')

asyncio.run(main())
